"""Summary across missions (docs/evaluation.md, "Across missions")."""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np

from frle import evaluate, qc
from frle.config import Config

MIN_PAIRS = 500
N_BOOT = 2000
SEED = 0
USED = ("prism_position", "dlio_map_odometry", "anymal_state_odometry", "cpt7_ie_tc_odometry")


def run(cfg: Config) -> dict:
    qc_by = {(r.mission, r.topic): r for r in qc.run(cfg)}
    missions, excluded = [], []
    for mission in cfg.missions:
        failing = [
            f"{t}: {sorted(c.name for c in r.checks if not c.passed and c.severity == 'fail')}"
            for (m, t), r in qc_by.items()
            if m == mission and t in USED and r.status == "fail"
        ]
        if failing:
            excluded.append(
                {"mission": mission, "estimator": "all", "reason": f"QC fail {failing}"}
            )
            continue
        try:
            res = evaluate.evaluate_mission(cfg, mission)
        except (ValueError, KeyError, FileNotFoundError) as err:
            excluded.append(
                {"mission": mission, "estimator": "all", "reason": f"evaluation error: {err}"}
            )
            continue
        kept = []
        for s in res["scores"]:
            if s["pairs"] < MIN_PAIRS:
                excluded.append(
                    {
                        "mission": mission,
                        "estimator": s["topic"],
                        "reason": f"{s['pairs']} pairs < {MIN_PAIRS}",
                    }
                )
            else:
                kept.append(s)
        res["scores"] = kept
        names = {s["topic"] for s in kept}
        res["paired"] = [p for p in res["paired"] if p["a"] in names and p["b"] in names]
        missions.append(res)

    per_est: dict[str, list[float]] = {}
    for res in missions:
        for s in res["scores"]:
            per_est.setdefault(s["topic"], []).append(s["rmse_m"])
    summary = {}
    for topic, values in per_est.items():
        v = np.array(values)
        summary[topic] = {
            "missions": len(v),
            "median_rmse_m": float(np.median(v)),
            "q25_m": float(np.percentile(v, 25)),
            "q75_m": float(np.percentile(v, 75)),
            "min_m": float(v.min()),
            "max_m": float(v.max()),
        }

    diffs = [
        p["rmse_diff_m"]
        for res in missions
        for p in res["paired"]
        if (p["a"], p["b"]) == ("dlio_map_odometry", "anymal_state_odometry")
    ]
    paired = {}
    if diffs:
        d = np.array(diffs)
        rng = np.random.default_rng(SEED)
        boot = np.median(rng.choice(d, size=(N_BOOT, len(d)), replace=True), axis=1)
        paired = {
            "a": "dlio_map_odometry",
            "b": "anymal_state_odometry",
            "missions": len(d),
            "a_better": int((d < 0).sum()),
            "b_better": int((d > 0).sum()),
            "median_diff_m": float(np.median(d)),
            "ci_m": evaluate.ci(boot),
        }
    return {"missions": missions, "excluded": excluded, "summary": summary, "paired": paired}


INTRO = (
    'Generated by `frle summary`. Protocol: docs/evaluation.md ("Across missions"). '
    "Per-mission tables: eval.md."
)


def paired_sentence(p: dict) -> str:
    return (
        f"DLIO better in {p['a_better']} of {p['missions']} missions, leg odometry better in "
        f"{p['b_better']}. Median per-mission RMSE difference (DLIO − leg) {p['median_diff_m']:+.3f} m, "
        f"95 % interval {p['ci_m'][0]:+.3f} to {p['ci_m'][1]:+.3f} m (missions resampled)."
    )


def _cell(by: dict, topic: str) -> str:
    return f"{by[topic]['rmse_m']:.3f}" if topic in by else "-"


def write_reports(result: dict, out_dir: Path) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "summary.json").write_text(json.dumps(result, indent=2) + "\n")
    evaluate.write_reports(result["missions"], out_dir)
    lines = [
        "# Summary across missions",
        "",
        INTRO,
        "",
        "## APE RMSE per mission (m)",
        "",
        "| Estimator | Missions | Median | 25 %–75 % | Min | Max |",
        "|---|---|---|---|---|---|",
    ]
    for topic, s in result["summary"].items():
        lines.append(
            f"| {topic} | {s['missions']} | {s['median_rmse_m']:.3f} | {s['q25_m']:.3f}–{s['q75_m']:.3f} | "
            f"{s['min_m']:.3f} | {s['max_m']:.3f} |"
        )
    p = result["paired"]
    if p:
        lines += [
            "",
            "## DLIO vs leg odometry, same prism timestamps",
            "",
            paired_sentence(p),
        ]
    lines += [
        "",
        "## Per mission (RMSE, m)",
        "",
        "| Mission | DLIO | Leg odometry | CPT7 | Prism pairs |",
        "|---|---|---|---|---|",
    ]
    for res in result["missions"]:
        by = {s["topic"]: s for s in res["scores"]}
        pairs = max((s["pairs"] for s in res["scores"]), default=0)
        lines.append(
            f"| {res['mission']} | {_cell(by, 'dlio_map_odometry')} | {_cell(by, 'anymal_state_odometry')} | "
            f"{_cell(by, 'cpt7_ie_tc_odometry')} | {pairs:,} |"
        )
    lines += ["", "## Excluded", ""]
    if result["excluded"]:
        lines += ["| Mission | Estimator | Reason |", "|---|---|---|"]
        lines += [
            f"| {e['mission']} | {e['estimator']} | {e['reason']} |" for e in result["excluded"]
        ]
    else:
        lines.append("None.")
    (out_dir / "summary.md").write_text("\n".join(lines) + "\n")
