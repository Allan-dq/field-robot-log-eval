"""Runs every seeded fault through the regression gate and writes reports/seeded_faults.{json,md}."""

import json

from frle.config import REPO
from frle.faults import run_all


def main() -> None:
    results = run_all()
    caught = sum(r["caught"] for r in results)
    out = REPO / "reports"
    (out / "seeded_faults.json").write_text(json.dumps(results, indent=2) + "\n")
    lines = [
        "# Seeded faults",
        "",
        f"Generated by `scripts/seeded_faults.py`. The gate caught **{caught} of {len(results)}** faults.",
        "Rules: config/gate.yaml, reasons: docs/regression_gate.md.",
        "",
        "| Fault | Kind | What was changed | Caught | First problem reported |",
        "|---|---|---|---|---|",
    ]
    for r in results:
        first = r["problems"][0].replace("|", "/") if r["problems"] else "-"
        lines.append(
            f"| {r['fault']} | {r['kind']} | {r['description']} | {'yes' if r['caught'] else '**no**'} | {first} |"
        )
    (out / "seeded_faults.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
